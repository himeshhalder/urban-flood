export function getCityData(cityId: string) {
  const city = ALL_SUPPORTED_CITIES.find(c => c.id === cityId) || ALL_SUPPORTED_CITIES[0];
  if (cityId === 'mumbai') {
    return {
      city,
      roads: MUMBAI_ROADS,
      drainageNodes: MUMBAI_DRAINAGE_NODES,
      drainageEdges: MUMBAI_DRAINAGE_EDGES,
      facilities: MUMBAI_FACILITIES,
      rainfallData: RAINFALL_NOWCAST_SERIES,
      alerts: INITIAL_ALERTS,
      arrivalZones: MUMBAI_ARRIVAL_ZONES,
      floodPolygons: MUMBAI_FLOOD_POLYGONS
    };
  }
  const { nodes, edges } = generateCityDrainage(city);
  return {
    city,
    roads: generateCityRoads(city),
    drainageNodes: nodes,
    drainageEdges: edges,
    facilities: generateCityFacilities(city),
    rainfallData: generateCityRainfall(city),
    alerts: generateCityAlerts(city),
    arrivalZones: generateCityArrivalZones(city),
    floodPolygons: generateCityFloodPolygons(city)
  };
}

